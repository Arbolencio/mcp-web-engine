"""Render captured MCP output as a readable replay, not a fabricated client UI.

Requires Pillow: uv run --with pillow python examples/render_demo.py
"""
import argparse
import json
import textwrap
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def render(session, target, font_path):
    data = json.loads(Path(session).read_text())
    responses = data['responses']
    if [r.get('id') for r in responses] != [1, 2, 3, 4, 5]:
        raise ValueError('Not a complete recorded session')
    if any(r.get('error') or r['result'].get('isError') for r in responses):
        raise ValueError('Refusing to illustrate failed calls as success')
    search, fetched, markdown = [json.loads(r['result']['content'][0]['text']) for r in responses[2:]]
    tools = [t['name'] for t in responses[1]['result']['tools']]
    scenes = [
        ('01 / CONNECT', ['$ uvx mcp-web-engine==1.2.1', '', 'MCP initialize -> ' + responses[0]['result']['serverInfo']['version'], 'tools/list -> ' + ', '.join(tools), '', 'stdio transport / real server replies', 'No model account used in this recording.']),
        ('02 / SEARCH', ['web_search', 'query: ' + search['query'], 'results: ' + str(search['count']), ''] + [str(item['rank']) + '. ' + item['title'] + '\n   ' + item['url'] for item in search['results']]),
        ('03 / FETCH', ['fetch_url', 'url: ' + fetched['url'], 'HTTP: ' + str(fetched['status_code']), 'bytes: ' + str(fetched['content_length']), '', 'HTML excerpt (first 320 characters):', fetched['content'][:320] + ('...' if len(fetched['content']) > 320 else '')]),
        ('04 / EXTRACT', ['extract_markdown', 'url: ' + markdown['url'], 'characters: ' + str(markdown['markdown_length']), '', markdown['markdown'], '', 'Returned by the server, not generated by an LLM.']),
        ('05 / YOUR AGENT', ['Search the web through your SearXNG instance.', 'Fetch a public page.', 'Turn HTML into text your agent can use.', '', 'Requires uv / Python >=3.11.', 'npm launcher also requires Node >=18.', 'Search requires SearXNG with JSON enabled.', '', 'mcp-web-engine 1.2.1 / MIT'])
    ]
    font = ImageFont.truetype(font_path, 20)
    small = ImageFont.truetype(font_path, 16)
    heading = ImageFont.truetype(font_path, 28)
    frames = []
    for label, content in scenes:
        frame = Image.new('RGB', (1120, 700), '#10151f')
        draw = ImageDraw.Draw(frame)
        draw.rounded_rectangle((18, 18, 1102, 682), radius=20, outline='#344050', width=2)
        draw.text((42, 40), 'MCP WEB ENGINE', font=heading, fill='#b9b4fb')
        draw.text((42, 88), label, font=small, fill='#63dbb0')
        y = 130
        for block in content:
            for line in block.split('\n'):
                for wrapped in textwrap.wrap(line, width=82, break_long_words=True) or ['']:
                    if y > 592:
                        raise ValueError('Scene would clip text; shorten or paginate it')
                    draw.text((42, y), wrapped, font=font, fill='#e3e9f0')
                    y += 27
        draw.line((42, 625, 1078, 625), fill='#344050', width=1)
        draw.text((42, 640), 'REAL CAPTURE / paced replay / not a GUI recording or benchmark', font=small, fill='#a9b4c4')
        frames.append(frame)
    target = Path(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    frames[0].save(target, save_all=True, append_images=frames[1:], duration=[7000] * len(frames), loop=0, optimize=True)
    frames[3].save(target.with_suffix('.png'))
    print(json.dumps({'gif': str(target), 'frames': len(frames), 'duration_seconds': 35, 'recorded_at': data['recorded_at']}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--session', default='docs/assets/demo-session.json')
    parser.add_argument('--output', default='docs/assets/demo.gif')
    parser.add_argument('--font', default='/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', help='Path to a Unicode TrueType font')
    args = parser.parse_args()
    render(args.session, args.output, args.font)
